import os
import stat

ENTRY = "Nimbostratford: drizzle until 10, sunshine by lunch, light winds — and the 8:15 bus is only nine minutes late, which counts as early here."

def main():
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "entry.txt")
    with open(path, "w", encoding="utf-8") as f:
        f.write(ENTRY)
    os.chmod(path, 0o644)

if __name__ == "__main__":
    main()
